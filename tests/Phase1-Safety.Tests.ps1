BeforeAll {
    $ProjectRoot = Split-Path -Parent $PSScriptRoot
    $Init = Get-Content -LiteralPath (Join-Path $ProjectRoot 'core\00-Initialize.ps1') -Raw
    $System = Get-Content -LiteralPath (Join-Path $ProjectRoot 'core\10-System.ps1') -Raw
    $Hardware = Get-Content -LiteralPath (Join-Path $ProjectRoot 'core\11-HardwareInspection.ps1') -Raw
    $HardwarePage = Get-Content -LiteralPath (Join-Path $ProjectRoot 'pages\06-HardwareInspection.ps1') -Raw
    $BackupPage = Get-Content -LiteralPath (Join-Path $ProjectRoot 'pages\05-Backup.ps1') -Raw
    $PackageWorker = Get-Content -LiteralPath (Join-Path $ProjectRoot 'tools\Run-SLT-Packages.ps1') -Raw
    $BoostPage = Get-Content -LiteralPath (Join-Path $ProjectRoot 'pages\04-Boost.ps1') -Raw
    $Startup = Get-Content -LiteralPath (Join-Path $ProjectRoot 'START_SLT_DIAGNOSTIC.ps1') -Raw
}
Describe 'SLT Smart PC Boost Phase 1 safety invariants' {
    It 'does not contain the previous hardcoded staff PIN or default password' {
        $Hardware | Should -Not -Match '2580|SLT@2026'
        $Init | Should -Not -Match '2580|SLT@2026'
    }

    It 'stores a salted PIN derivation record instead of a plaintext PIN' {
        $Hardware | Should -Match 'PBKDF2-HMAC-SHA1'
        $Hardware | Should -Match 'RandomNumberGenerator'
        $Hardware | Should -Match 'SetAccessRuleProtection\(\$true'
    }

    It 'does not automatically delete duplicate-looking files or the Public Desktop shortcut' {
        $Init | Should -Match 'Detect duplicate-looking downloaded files without changing or deleting user data'
        $Init | Should -Not -Match 'Remove-Item[^\r\n]*SMART PC BOOST\.lnk'
        $Init | Should -Not -Match 'Remove-Item[^\r\n]*SLT Smart Tools Hub\.lnk'
        $Init | Should -Match 'if \(Test-Path -LiteralPath \$lnkPath\) \{ Log-SLT'
        $PackageWorker | Should -Not -Match 'Remove-Item[^\r\n]*SLT Smart Tools Hub\.url'
        $Startup | Should -Match 'left untouched'
    }

    It 'restricts machine-wide state and log folders to trusted principals' {
        $Init | Should -Match 'StateAclProtected'
        $Init | Should -Match 'SetAccessRuleProtection\(\$true'
        $Init | Should -Match 'BUILTIN\\Administrators'
    }

    It 'does not automatically remove Mark-of-the-Web from downloaded scripts or binaries' {
        $Init | Should -Not -Match 'Unblock-File'
        $Startup | Should -Not -Match 'Unblock-File'
    }

    It 'does not decrypt the Windows OS volume' {
        $System | Should -Not -Match 'manage-bde(?:\.exe)?\s+-off\s+C:'
        $System | Should -Match 'Suspend-BitLocker'
        $System | Should -Match 'EncryptionPercentage'
    }

    It 'does not delete pending reboot markers or force Sysprep registry state' {
        $repair = [regex]::Match($System, '(?s)function Repair-SLTSysprepEnvironment.*?function Suspend-SLTBitLockerForSysprep').Value
        $repair | Should -Not -Match 'Remove-Item[^\r\n]*RebootPending|Remove-ItemProperty[^\r\n]*PendingFileRenameOperations|Set-ItemProperty[^\r\n]*GeneralizationState'
    }

    It 'does not remove Appx packages automatically during Sysprep readiness review' {
        $repair = [regex]::Match($System, '(?s)function Repair-SLTSysprepEnvironment.*?function Suspend-SLTBitLockerForSysprep').Value
        $repair | Should -Not -Match 'Remove-AppxPackage|Remove-AppxProvisionedPackage'
        $System | Should -Match 'Confirm Windows App Removal'
    }

    It 'preserves Windows Prefetch and Windows Update download cache' {
        $System | Should -Not -Match 'Remove-Item[^\r\n]*Prefetch'
        $System | Should -Not -Match 'SoftwareDistribution\\Download[^\r\n]*Remove-Item'
        $System | Should -Match 'Windows Update download cache is preserved'
    }

    It 'does not delete arbitrary external Panther Unattend files' {
        $BackupPage | Should -Match 'Generated by SLT Smart PC Boost\.'
        $BackupPage | Should -Match 'external Panther'
    }

    It 'requires an explicit keyboard pass only after required keys are tested' {
        $Hardware | Should -Match 'missingRequired'
        $Hardware | Should -Match 'Complete all required keys to enable Pass'
        $HardwarePage | Should -Not -Match 'Mark All Pending as Passed'
    }

    It 'does not mark unknown or pending QC as passed by default' {
        $Hardware | Should -Match 'PENDING / NOT TESTED'
        $HardwarePage | Should -Match "else \{ 'Pending' \}"
        $HardwarePage | Should -Match 'Reset All QC to Pending'
    }

    It 'preserves WinGet source after normal package queues' {
        $PackageWorker | Should -Match 'Preserve Microsoft.WinGet.Source'
        $PackageWorker | Should -Not -Match "Get-AppxPackage -Name '\*Microsoft\.Winget\.Source\*'.*Remove-AppxPackage"
        $PackageWorker | Should -Not -Match 'Remove-Item -LiteralPath \$psPathVal'
        $PackageWorker | Should -Match 'Potentially stale uninstall registry entry preserved'
    }

    It 'does not use force for normal WinGet uninstall commands' {
        $PackageWorker | Should -Not -Match "'uninstall'.*'--force'"
    }

    It 'backs up existing scheduled tasks before replacing or deleting them' {
        $System | Should -Match 'Export-SLTTaskDefinition'
        $System | Should -Match 'Confirm Scheduled Task Replacement'
        $BoostPage | Should -Match 'Export-SLTTaskDefinition'
        $BoostPage | Should -Match 'Confirm Auto-Maintenance Task Change'
        $BoostPage | Should -Match 'Run-SLT-Boost-AutoMaintenance.ps1'
    }

    It 'preserves registry backup entries when restoration fails' {
        $System | Should -Match 'backup retained'
        $System | Should -Match '\$remaining\[\$p\.Name\]'
    }
}

